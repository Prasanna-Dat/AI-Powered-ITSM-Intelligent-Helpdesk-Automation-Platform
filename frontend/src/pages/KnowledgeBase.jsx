import { useEffect, useMemo, useState } from "react";
import { api } from "../api";
import { Sources } from "../components/ui.jsx";

export default function KnowledgeBase() {
  const [articles, setArticles] = useState([]);
  const [cat, setCat] = useState("All");
  const [open, setOpen] = useState(null);
  const [q, setQ] = useState("");
  const [res, setRes] = useState(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => { api.kbArticles().then(setArticles); }, []);
  const cats = useMemo(() => ["All", ...new Set(articles.map((a) => a.category))], [articles]);
  const shown = articles.filter((a) => cat === "All" || a.category === cat);

  const search = async (e) => {
    e.preventDefault();
    if (!q.trim()) return;
    setBusy(true);
    try { setRes(await api.kbSearch(q)); } finally { setBusy(false); }
  };

  return (
    <section className="page">
      <header className="page-head">
        <h2>Knowledge Base</h2>
        <p>Approved IT articles. Search runs the full RAG pipeline: embed, vector search, grounded answer.</p>
      </header>

      <form className="composer" onSubmit={search}>
        <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search the knowledge base, for example: wifi keeps disconnecting" />
        <button className="btn primary" disabled={busy || !q.trim()}>Search</button>
      </form>

      {res && (
        <div className="panel">
          <h3>RAG answer</h3>
          <pre className="answer-pre">{res.answer}</pre>
          <p className="muted small">Top similarity {res.top_score} · generated by {res.answer_generated_by}</p>
          <h4>Sources used</h4>
          <Sources sources={res.sources} />
          <h4>Retrieved chunks</h4>
          {res.chunks.map((c) => (
            <details key={c.chunk_id}><summary>{c.chunk_id} · {c.title} · {c.section} · score {c.score}</summary><pre>{c.text}</pre></details>))}
        </div>)}

      <div className="chips">
        {cats.map((c) => <button key={c} className={cat === c ? "on" : ""} onClick={() => setCat(c)}>{c}</button>)}
      </div>
      <div className="split">
        <ul className="list">
          {shown.map((a) => (
            <li key={a.id}>
              <button className={open?.id === a.id ? "on" : ""} onClick={() => api.kbArticle(a.id).then(setOpen)}>
                <span>{a.id} · {a.title}</span>
                <span className="muted small">{a.category} · {a.chunks} chunks · {a.words} words</span>
              </button>
            </li>))}
        </ul>
        <div className="detail">
          {open ? (<><h3>{open.title}</h3><p className="muted small">{open.id} · {open.category} · tags: {open.tags.join(", ")}</p>
            <pre className="article">{open.body}</pre></>) : <p className="empty">Choose an article to read it.</p>}
        </div>
      </div>
    </section>
  );
}
